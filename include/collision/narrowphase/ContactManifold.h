#pragma once
// Точки контакта пары тел: все вершины площадки касания за один вызов.
//
// Контакт «грань к грани» — это многоугольник: грань одного тела, обрезанная по контуру грани
// другого. Его вершины и есть точки контакта. Опоре достаточно четырёх: из многоугольника
// оставляются самая глубокая точка и те, что вместе с ней охватывают наибольшую площадь.
// Контакт скрещённых рёбер — одна точка.

#include <collision/shapes/Flat.h> // kOnBoundary — допуск границы грани
#include <math/SmallVector.h>
#include <math/Vector3.h>

#include <cstdint>
#include <vector>

namespace kp {

struct ContactPoint {
    Vector3 onA, onB;    // точки на поверхностях тел, мир
    Real separation;  // расстояние между ними вдоль нормали; отрицательное — тела перекрылись
    // Какими элементами тел образована точка. Один и тот же контакт на соседних шагах получает
    // один и тот же номер — по нему переносится накопленный импульс.
    std::uint32_t id;
};

struct ContactManifold {
    Vector3 normal; // единичная, от A к B, мир
    // Все вершины площадки касания и все точки, которые коснутся следующими (с зазором до запаса):
    // сначала касающиеся, за ними остальные по возрастанию зазора. Число точек не ограничено:
    // скорость сближения линейна по положению, поэтому удар и силы, остановившие сближение во
    // всех вершинах площадки, остановили его на всей площадке (proofs/vertices_bound_patch.smt2),
    // а любой набор из меньшего числа точек такой гарантии не даёт — пятая вершина пятиугольной
    // площадки может сближаться, когда четыре другие стоят.
    SmallVector<ContactPoint, 8> points;
    int count = 0; // число точек; меняется только через add
    // Грань, над которой лежат точки, принадлежит телу B; иначе — телу A. У многообразия из одной
    // точки (пара рёбер, скруглённая форма) значения не имеет.
    bool faceOnB = false;
    // Радиус качения каждого тела в месте контакта. У круглого тела точка касания не привязана к
    // телу: она перекатывается по поверхности, а вместе с телом движется точка его ядра — центр
    // шара, ось капсулы и цилиндра, — лежащая под поверхностью на этом расстоянии. У многогранника
    // касается сама вершина, радиус нулевой.
    Real roundA = 0, roundB = 0;

    void add(const ContactPoint& point) {
        points.push_back(point);
        count = int(points.size());
    }
};

} // namespace kp
