#pragma once
// Пары тел, которые касаются или могут коснуться за шаг, и точки контакта между ними.

#include <body/Body.h>
#include <collision/narrowphase/ContactManifold.h>

#include <optional>
#include <vector>

namespace kp {

// Расстояние, на котором тела считаются соприкоснувшимися. Полоса касания нужна поиску времени
// удара: он останавливает тела внутри неё, не доводя до перекрытия.
constexpr Real kContactDistance = Real(1e-4); // м

// Допуск перекрытия: на сколько телам разрешено войти друг в друга. Пока перекрытие мельче,
// шаг идёт дальше, а в начале следующего отрезка тела раздвигаются псевдоскоростями — сдвигом и
// поворотом поз без изменения настоящих скоростей (OverlapSeparation); раздвигание
// срабатывает с половины допуска и возвращает тела к нулю. Отрезок шага обрывается, только когда
// перекрытие дошло бы до допуска (EventSearch.cpp, crossingStart).
//
// Величина — 10 мкм: в десять раз меньше полосы касания и в пятьсот раз меньше допуска Box3D
// (5 мм). При допуске в микрон шаг дробился вдесятеро чаще, а там, где контакт не видит места
// сближения, не кончался: на выборке таблицы случаев шагов без конца было 127 при 1 мкм, 89 при
// 10 мкм и 72 при 100 мкм. Цена допуска — энергия и момент импульса, которые добавляет
// раздвигание: клеток с приростом энергии 132, 146 и 156 соответственно.
constexpr Real kOverlap = Real(1e-5); // м

struct ContactPair {
    int a = 0, b = 0;      // номера тел; нормаль многообразия направлена от a к b
    int partA = 0, partB = 0; // номера частей этих тел (Body::part); у простого тела часть одна
    Real distance = 0;     // между поверхностями в начале шага
    Real reach = 0;        // насколько тела могут сблизиться за шаг: граница скорости сближения × время
    ContactManifold manifold;     // пусто, если тела дальше запаса

    bool inContact() const { return distance <= kContactDistance; }
};

// Верхняя граница скорости любой точки тела — что бы ни происходило с его ориентацией, пока
// импульсы прежние. От неё зависит, насколько далеко поиск времени удара может шагнуть, не
// рискуя пропустить столкновение: завышенная граница делает шаги мелкими, заниженная была бы
// ошибкой. Поэтому граница строгая, но учитывает форму тела по главным осям.
Real maxPointSpeed(const Body& body);
// Скорость, которую приложенные к телу сила и момент (Body::force, torque) добавят его точке за время h,
// не больше: |F| h / m + |τ| h · (наибольший I⁻¹) · R, R — охватывающий радиус. Прибавляется к
// maxPointSpeed там, где считается путь тела за шаг: иначе тело, разогнанное силой, прошло бы мимо пары.
Real forcedSpeedGain(const Body& body, Real h);

// На сколько тела вошли друг в друга; ноль и меньше — не вошли. У двух многогранников глубину
// даёт разделяющая ось. У скруглённых форм расстояние между ядрами знает глубину, пока сами ядра
// разделены. Если ядра перекрылись, у пары «многогранник — круглая форма» глубину даёт контакт
// по грани многогранника; у двух круглых форм её взять неоткуда, и они считаются вошедшими на
// радиус. Глубина обязана расти от нуля непрерывно: если бы касание ядер сразу значило
// «перекрытие», как было у острого цилиндра на многограннике, шаг подбирался бы к моменту
// касания без конца.
Real overlapDepth(const Body& a, const Body& b);

// Расстояние между телами со знаком (отрицательное — глубина перекрытия) и направление от a к b,
// вдоль которого оно измерено. Глубина — та же, что у overlapDepth.
struct Separation {
    Real distance = 0;
    Vector3 normal;
};
Separation separationOf(const Body& a, const Body& b);

// Зазор между телами вдоль единичного направления n (от a к b): насколько их можно сдвинуть
// навстречу вдоль n до касания; отрицательный — на сколько они перекрыты вдоль n. Это расстояние
// между двумя опорными плоскостями с нормалью n. Зазор вдоль любого направления не больше
// расстояния со знаком (proofs/plane_gap_bounds_distance.smt2), поэтому он — надёжная нижняя
// граница, а считается одной опорной точкой каждого тела.
Real gapAlong(const Body& a, const Body& b, Vector3 n);

// Пара выпуклых тел (или частей составных тел), если за время h они могут сблизиться до касания:
// проверка по охватывающим шарам, затем точное расстояние и точки контакта. Номера тел и частей
// вписывает вызывающий.
std::optional<ContactPair> examinePair(const Body& a, const Body& b, Vector3 gravity, Real h, Real boundary = kOnBoundary);
// Путь сближения пары за время h при наибольших скоростях точек тел speedA и speedB (maxPointSpeed):
// (speedA + speedB + g h) h — за время h сила тяжести добавляет к скорости не больше g h.
inline Real approachReach(Real speedA, Real speedB, Vector3 gravity, Real h) { return (speedA + speedB + gravity.length() * h) * h; }
// То же, что examinePair, когда путь сближения reach уже посчитан: поиск пар считает наибольшую
// скорость точки раз на тело, а не на каждую его пару.
std::optional<ContactPair> examinePairWithin(const Body& a, const Body& b, Real reach, Real boundary = kOnBoundary);
// То же для простых тел i и j.
std::optional<ContactPair> examinePair(const std::vector<Body>& bodies, int i, int j, Vector3 gravity, Real h, Real boundary = kOnBoundary);

} // namespace kp
