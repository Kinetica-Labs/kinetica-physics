#pragma once
// Шаг с постоянной ценой кадра: решатель с проходами по контактам, устроенный как в Box3D
// (research/refs/box3d/src/contact_solver.c, solver.c — «Soft Step» Эрина Катто).
//
// Кадр делится на подшаги. В каждом: скорости получают тяжесть; к ним прикладываются импульсы,
// накопленные раньше (тёплый старт); один проход по сочленениям и контактам с мягкой поправкой
// положения; тела сдвигаются; ещё один проход без поправки — он снимает скорость, которую
// поправка добавила, и считает трение. Число действий на кадр от происходящего в сцене не зависит.
//
// Контакт ставится заранее, по зазору: точке, до которой ещё s метров, разрешено сближаться не
// быстрее s / h, поэтому тело не пролетает сквозь другое, а шаг не рвётся на ударах. Перекрытие
// убирается мягко — как пружиной с частотой contactHertz и затуханием contactDamping, — и не
// быстрее pushSpeed. Трение пары приложено в центре её точек: сила в касательной плоскости и
// момент вокруг нормали (так же в ReactPhysics3D и Jolt).
//
// Площадка контакта находится раз в обновление и к его концу устаревает, поэтому сдвиг тел в подшаге
// пробный: если после него пара вошла глубже, чем вела её решённая задача, по новой площадке
// добавляется контакт, тела возвращаются и нормали решаются снова (MissedContacts).
//
// Нормали островка решаются одной жёсткой задачей (IslandNormals): стопка, пирамида и куб в тонну
// на лёгких кубах стоят без провисания, удар по лежащему телу доходит до опоры в том же подшаге.
// Только очень большие островки решаются парами на пружинах — там шаг приближённый: за кадр импульсы
// проходят вдоль цепочки контактов на конечное число звеньев. Трение везде решается обходом пар.
// Точный шаг (World::step без realtime) остаётся эталоном, по которому меряется ошибка этого.

#include <math/StepMemory.h>
#include <collision/ContactPair.h>
#include <dynamics/ContactForces.h>
#include <dynamics/StepStage.h>
#include <joints/JointSet.h>

#include <vector>

namespace kp {

class SoftStep {
public:
    int substeps = 8;
    // Сколько раз за шаг мира заново ищутся пары, точки и нормали контакта (World::step); подшаги
    // делятся между обновлениями поровну. За время между обновлениями тело проходит путь, на
    // котором новая грань удара в площадку ещё не попала: при одном обновлении на кадр перекрытие
    // при ударе доходило до пути за кадр (куча — 110 мм). В тихом кадре, где ни одно тело не проходит
    // больше contactDrift, обновление одно (World::quiet): в покое четыре поиска ничего не меняют.
    int contactUpdates = 4;
    // Второе решение нормалей подшага, без поправки положения, снимает скорость, добавленную
    // выталкиванием. Его получают только контакты тел, которые движутся быстрее restSpeed, м/с (скорость
    // точки тела; мир задаёт её как contactDrift за кадр): в покое оно стоит 17 % кадра и меняет только
    // осадку больших куч на пружинах — на 1 % (замеры H71, H72). Ноль — второе решение у всех.
    Real restSpeed = 0;
    // Жёсткость контакта, Гц; не больше восьмой доли частоты подшагов. Мягкий контакт — пружина,
    // и высокая стопка на таких пружинах теряет устойчивость: при 30 Гц десять кубов с ребром
    // 20 см, поставленных друг на друга, заваливались за три секунды.
    Real contactHertz = 60;
    Real contactDamping = 10; // доля критического затухания
    Real pushSpeed = 3;      // м/с: быстрее перекрытие не выталкивается
    // Глубина, м: если после сдвига тела вошли друг в друга глубже, чем знают точки их контакта,
    // больше чем на неё, подшаг повторяется с новым контактом (MissedContacts). Мельче — уберёт
    // поправка положения на следующих подшагах.
    Real recheckDepth = Real(1e-3);
    // Нормали всех точек контакта решаются одной жёсткой задачей (IslandNormals), пока точек не
    // больше этого числа; иначе — парами, на пружинах contactHertz. Ноль — всегда парами.
    int directContactRows = 512;
    // Жёсткость связей сочленений. Под нагрузкой F связь расходится на F / (m ω²), ω = 2π · частота:
    // чем выше частота, тем меньше провисание; выше четверти частоты подшагов шаг расходится.
    Real jointHertz = 120, jointDamping = 2;
    // От пары тел в решатель идут четыре точки контакта, а не все вершины площадки: меньше работы
    // и меньше шума. Выключается там, где нужна вся площадка, — в робототехнике.
    bool fourContactPoints = true;
    Real edgeSlop = Real(1e-3); // м: запас на совпадающие рёбра и грани (PairFinder::boundary)
    // Допуск, м: площадка пары многогранников идёт за телами без нового поиска, пока относительный
    // сдвиг пары с момента поиска не больше него (ManifoldMemory). Ноль — искать при любом сдвиге.
    Real contactDrift = Real(2e-4);
    // Запертые свободы сочленений решаются одной системой, точно (DirectJoints), а не проходами
    // по одной связи; jointCorrection — какую долю нарушения положения связь убирает за подшаг.
    bool directJoints = true;
    Real jointCorrection = 1;
    Real bounceSpeed = 1;    // м/с: медленнее этого удар отскока не даёт
    // Плечо трения качения δ, м: контакт сопротивляется качению моментом до δ N (SoftContact::solveRolling).
    // Ноль — потерь на качение нет, и качнувшаяся цепь или катящийся шар не останавливаются никогда; у
    // стали по стали δ — сотые доли миллиметра, у мягкого колеса — миллиметры.
    Real rollingResistance = 0;
    // Наблюдатель стадий шага (StepStage) — для приборов времени; пустой никого не зовёт.
    StageObserver observer;

    // Продвигает тела на dt. contactMemory и jointMemory — накопленные импульсы прошлого кадра для
    // тёплого старта; на выходе в них импульсы этого.
    void step(std::vector<Body>& bodies, const std::vector<ContactPair>& pairs, const JointSet& joints, Vector3 gravity, Real dt, ContactForces& contactMemory,
              std::vector<std::vector<Real>>& jointMemory) const;
};

} // namespace kp
