#pragma once
// Толчок телам мира внутри шара действия: взрыв (от центра) и толчок в одном направлении. Так же устроены
// AddRadialImpulse в Unreal и AddExplosionForce в Unity; в редакторах (Houdini, Cinema 4D, Maya, Blender) это
// отдельный предмет сцены — «сила» с шаром действия, спадом и временем действия.
//
// Тело задето, если его ближайшая к центру точка лежит в шаре. Доля импульса падает с расстоянием d до
// этой точки: w = (1 − d / radius)^falloff; falloff = 0 — без спада, 1 — линейный, 2 — квадратичный.
//   взрыв:  импульс w · impulse вдоль луча от центра к ближайшей точке тела, приложен в ней — тело,
//           задетое не по центру, закручивается;
//   толчок: импульс w · impulse (вектор), приложен в центре масс — тело не закручивается.
// Импульс — в Н·с: лёгкое тело улетает быстрее тяжёлого. Сила F, действующая постоянно, — тот же вызов
// каждый шаг мира с импульсом F · dt. Спящее тело будится, неподвижное не трогается; тела обходятся по
// номерам. Вызывать между шагами мира.

#include <world/World.h>

