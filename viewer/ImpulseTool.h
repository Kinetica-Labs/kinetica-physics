#pragma once
// Источник импульса в окне: взрыв (толчок от центра) или толчок в направлении. Шар действия и стрелки
// рисуются в сцене; «пуск» зовёт applyRadialImpulse или applyDirectedImpulse (world/AreaImpulse.h). Так же
// в редакторах: сила — отдельный предмет сцены со своим шаром действия, спадом и временем действия.

#include <debug/DebugGeometry.h>
#include <world/AreaImpulse.h>

struct ImpulseTool {
    bool radial = true;            // взрыв; иначе толчок в направлении
    kp::Vector3 center{0, 0.5, 0}; // центр шара действия, м
    float radius = 1.5f;           // радиус шара действия, м
    float impulse = 1000;          // импульс, Н·с; у постоянно действующего — сила, Н
    int falloff = 1;               // степень спада с расстоянием: 0 — без спада
    float yaw = 0, pitch = 0.5f;   // направление толчка: поворот вокруг вертикали и подъём, рад
    bool everyFrame = false;       // действует постоянно: каждый кадр импульс «сила × время кадра»
    int touched = 0;               // сколько тел задел последний пуск кнопкой — для панели

    kp::Vector3 direction() const;
    // Толкает тела мира; share — доля импульса (у постоянной силы — время кадра). Возвращает число задетых тел.
    int fire(kp::World& world, kp::Real share = 1) const;
    // Шар действия тремя окружностями; у толчка — стрелка из центра длиной в радиус, у взрыва — шесть стрелок наружу.
    void draw(kp::DebugGeometry& geometry) const;
};
